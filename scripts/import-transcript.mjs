import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { normalizeTranscriptProvenance, parseTranscript } from "./lib/transcript.mjs";

function parseArgs(values) {
  const args = {};
  for (let index = 0; index < values.length; index += 1) {
    const value = values[index];
    if (!value.startsWith("--")) continue;
    args[value.slice(2)] = values[index + 1];
    index += 1;
  }
  return args;
}

const args = parseArgs(process.argv.slice(2));
const required = [
  "input",
  "episode-id",
  "source-id",
  "title",
  "url",
  "language",
  "publisher-name",
  "publisher-url",
  "speakers",
  "attribution-status",
  "source-role",
  "attribution-note",
];
const missing = required.filter((key) => !args[key]);

if (missing.length) {
  console.error(`Arguments manquants : ${missing.map((key) => `--${key}`).join(", ")}`);
  process.exit(1);
}

const inputPath = path.resolve(args.input);
const outputPath = path.resolve(
  args.output ?? path.join(".workbench", "transcripts", `${args["episode-id"]}.json`),
);
const input = await readFile(inputPath, "utf8");
const segments = parseTranscript(input, args.format ?? "auto");
const provenance = normalizeTranscriptProvenance({
  publisherName: args["publisher-name"],
  publisherUrl: args["publisher-url"],
  speakers: args.speakers.split("|").map((speaker) => speaker.trim()).filter(Boolean),
  attributionStatus: args["attribution-status"],
  sourceRole: args["source-role"],
  attributionNote: args["attribution-note"],
});

const transcript = {
  schemaVersion: 2,
  episodeId: args["episode-id"],
  sourceId: args["source-id"],
  title: args.title,
  url: args.url,
  language: args.language,
  provenance,
  acquisition: {
    method: args.method ?? "provided-file",
    isAutoGenerated: args.auto === "true",
    importedAt: new Date().toISOString(),
    originalFilename: path.basename(inputPath),
  },
  segments,
};

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, `${JSON.stringify(transcript, null, 2)}\n`, "utf8");
console.log(`${segments.length} segments importés vers ${outputPath}`);
console.log("Ce fichier de travail contient la transcription complète et ne doit pas être commité.");
